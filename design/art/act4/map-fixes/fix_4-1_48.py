# 4-1 48px 손질: 고친 길 그림(path_calm 뒤)에 (1) 착지 왼쪽 위 두 칸에 덮인 풀을 길로 (2) 튀어나온 길 칸 모서리 둥글리기
# (3) 낮은 안개: 막힌 칸에만, 아래(골짜기)와 맵 가장자리에 짙고 위 오른쪽은 엷게, 단 사이에는 띠처럼 흐르는 엷은 안개.
# 쓰기: $PY design/art/act4/map-fixes/fix_4-1_48.py IN.png OUT.png
import sys, os
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fog as F
src, out = sys.argv[1:3]
im, a, pal, rows, ex = F.load(src, '4-1')
T = 48
# (1) (10,1)은 위 가장자리가 고른 길: (9,1)에 그대로, (8,1)은 (10,1)에 (8,2)의 왼쪽 가장자리 14px를 얹어서
t101 = a[1*T:2*T, 10*T:11*T].copy()
a[1*T:2*T, 9*T:10*T] = t101
t = t101.copy(); t[:, :14] = a[2*T:3*T, 8*T:8*T + 14]
a[1*T:2*T, 8*T:9*T] = t
# (2)
F.round_notches(a, rows, T)
# (3)
H, W = a.shape
walk = F.walk_mask(rows, ex, T)
items = [  # (cx, cy, rx, ry, 세기) 칸 단위
    (6, 21.8, 7.5, 2.0, 1.0), (16.5, 22.8, 5.5, 1.6, 1.0), (27.5, 22.6, 6, 1.7, 1.0),   # 맨 아래 골짜기
    (1.6, 13.5, 2.4, 4.5, 1.0), (1.6, 20.5, 2.6, 3.2, 1.0),                             # 왼쪽 비탈
    (30.4, 11.5, 2.2, 4.5, 1.0), (30.4, 19.5, 2.4, 3.0, 1.0),                           # 오른쪽 비탈
    (9.5, 18.8, 5.0, 1.1, 0.9), (24.5, 13.7, 3.8, 0.8, 0.8), (7.5, 8.8, 3.0, 0.7, 0.7),  # 단 사이 낮은 띠
    (2.0, 3.0, 2.2, 2.2, 0.75), (29.5, 2.5, 2.0, 1.5, 0.6),
]
clear = [(6, 11.5, 12, 15), (22.3, 8, 24.7, 10), (15.3, 16.3, 17.7, 18), (11, 2.8, 16.5, 5)]  # 찻집·화로, 푯말, 돌무더기, 꺾인 나무
cov = F.fog(a, pal, walk, F.banks(H, W, T, items, 41, clear))
print(f'안개가 깔린 막힌 곳 비율 {cov:.2f}')
F.save(a, pal, out)
